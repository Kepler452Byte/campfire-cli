import { readFile, writeFile } from "node:fs/promises"
import { join } from "node:path"
import { expect, test } from "@playwright/test"

test("脚本项目的文件标签、只读高亮、刷新和失败恢复", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  await page.goto("/app/jobs/seed")
  await page.getByRole("button", { name: "查看脚本", exact: true }).click()
  await expect(page).toHaveURL(/\/app\/scripts\/growth/)
  const tree = page.getByLabel("脚本文件树", { exact: true })
  const source = page.getByLabel("脚本源码", { exact: true })
  await expect(tree.getByRole("button", { name: "刷新脚本" })).toBeVisible()
  await expect(source.getByRole("button", { name: /复制|刷新/ })).toHaveCount(0)
  await expect(tree.getByText("node_modules", { exact: true })).toHaveCount(0)
  await tree.getByText("daily.py", { exact: true }).click()
  const daily = page.getByLabel("源码 daily.py", { exact: true })
  await expect(daily).toContainText("def main():")
  await expect(daily).toHaveAttribute("contenteditable", "false")
  await expect(daily.locator(".cm-line span").first()).toBeVisible()
  await daily.click()
  await daily.press("Control+f")
  await expect(page.locator(".cm-search input[name='search']")).toBeVisible()
  await page.locator(".cm-search input[name='search']").fill("main")
  await page.locator(".cm-search input[name='search']").press("Escape")
  await tree.getByText("helpers", { exact: true }).click()
  await tree.getByText("study.py", { exact: true }).click()
  const study = page.getByLabel("源码 helpers/study.py", { exact: true })
  await expect(study).toContainText("学习记录")
  await expect(page.getByRole("tab")).toHaveCount(2)
  await page.getByRole("tab", { name: "daily.py", exact: true }).click()
  await expect(daily).toBeVisible()
  const tags = page.locator(".tags-view-container")
  await tags.getByRole("link", { name: "预置任务", exact: true }).click()
  await page.getByRole("button", { name: "查看脚本", exact: true }).click()
  await expect(tags.getByRole("link", { name: "脚本 · growth", exact: true })).toHaveCount(1)
  await expect(page.getByRole("tab")).toHaveCount(2)
  await page.getByRole("tab", { name: "study.py", exact: true }).click()

  const root = (await (await page.request.get("/api/v1/scripts")).json()).data.root as string
  expect(root).toContain("campfire-web-e2e-")
  const file = join(root, "growth", "helpers", "study.py")
  const original = await readFile(file, "utf8")
  try {
    await writeFile(file, "def collect():\n    return 'Agent 更新后的脚本'\n")
    await tree.getByRole("button", { name: "刷新脚本" }).click()
    await expect(study).toContainText("Agent 更新后的脚本")
    await expect(tree.getByText("study.py", { exact: true })).toBeVisible()
    await page.route("**/scripts/growth/file?**", route => new URL(route.request().url()).searchParams.get("path") === "helpers/study.py"
      ? route.fulfill({ status: 404, contentType: "application/json", body: JSON.stringify({ code: 404, message: "文件不存在", data: { status: "error", code: "not-found" } }) })
      : route.continue())
    await tree.getByRole("button", { name: "刷新脚本" }).click()
    await expect(source.getByRole("alert")).toContainText("文件无法预览")
    await expect(study).toHaveCount(0)
    await page.unroute("**/scripts/growth/file?**")
    await tree.getByRole("button", { name: "刷新脚本" }).click()
    await expect(study).toContainText("Agent 更新后的脚本")
    await expect(page.locator(".el-message--error")).toHaveCount(0)
    await page.screenshot({ path: "test-results/script-project.png", fullPage: true, animations: "disabled" })
    await page.setViewportSize({ width: 390, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(tree.getByRole("button", { name: "刷新脚本" })).toBeVisible()
    await expect(study).toBeVisible()
    await page.screenshot({ path: "test-results/script-project-mobile.png", fullPage: true, animations: "disabled" })
    await tree.getByText("unknown.custom", { exact: true }).click()
    await expect(page.getByLabel("源码 unknown.custom", { exact: true })).toContainText("plain text")
    await tree.getByText("binary.bin", { exact: true }).click()
    await expect(source.getByRole("alert")).toContainText("文件无法预览")
    expect(errors).toEqual([])
  } finally {
    await writeFile(file, original)
  }
})

test("任务编辑保存和清除脚本项目关联", async ({ page }) => {
  await page.goto("/app/jobs/seed")
  await page.getByRole("button", { name: "编辑", exact: true }).click()
  const dialog = page.getByRole("dialog")
  await expect(dialog.getByRole("combobox", { name: "脚本项目", exact: true })).toBeVisible()
  await dialog.getByRole("button", { name: "预览变更", exact: true }).click()
  await expect(dialog).toContainText("growth")
  await dialog.getByRole("button", { name: "确认保存", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const job = (await (await page.request.get("/api/v1/jobs/seed")).json()).data.job
  expect(job.script_project).toBe("growth")
  await page.getByRole("button", { name: "编辑", exact: true }).click()
  await dialog.locator(".el-form-item").filter({ has: page.getByRole("combobox", { name: "脚本项目", exact: true }) }).locator(".el-select").hover()
  await dialog.locator(".el-form-item").filter({ has: page.getByRole("combobox", { name: "脚本项目", exact: true }) }).locator(".el-select__clear").click()
  await dialog.getByRole("button", { name: "预览变更", exact: true }).click()
  await dialog.getByRole("button", { name: "确认保存", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect((await (await page.request.get("/api/v1/jobs/seed")).json()).data.job.script_project).toBeUndefined()
  await expect(page.getByRole("button", { name: "查看脚本", exact: true })).toHaveCount(0)
})
