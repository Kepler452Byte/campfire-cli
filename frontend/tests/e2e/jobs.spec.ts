  await page.getByRole("button", { name: "立即执行", exact: true }).click()
  const confirmation = page.locator(".el-message-box")
  await expect(confirmation).toBeVisible()
  const modal = await confirmation.boundingBox()
  expect(modal!.x).toBeGreaterThan(100)
  expect(modal!.y).toBeGreaterThan(100)
  await page.screenshot({ path: "test-results/job-confirmation.png", fullPage: true, animations: "disabled" })
  await page.getByRole("button", { name: "确认", exact: true }).click()
  await expect(page.getByLabel("运行日志")).toContainText("浏览器执行成功")
  await expect(page.getByRole("tab")).toHaveCount(2)
  await expect(page.getByRole("tab", { name: "stdout", exact: true })).toHaveAttribute("aria-selected", "true")
  await expect(page.getByLabel("运行日志")).not.toContainText("执行进度提示")
  const logTabs = await page.getByRole("tablist").boundingBox()
  const logContent = await page.getByLabel("运行日志").boundingBox()
  expect(logTabs!.y + logTabs!.height).toBeLessThanOrEqual(logContent!.y)
