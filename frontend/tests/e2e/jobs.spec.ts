  await page.screenshot({ path: "test-results/job-detail.png", fullPage: true, animations: "disabled" })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.screenshot({ path: "test-results/job-logs-mobile.png", fullPage: true, animations: "disabled" })
