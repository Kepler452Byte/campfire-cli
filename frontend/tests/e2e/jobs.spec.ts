  await dialog.getByLabel("名称", { exact: true }).fill("浏览器测试任务")
  await dialog.getByLabel("任务 ID", { exact: true }).fill("browser-test")
  await dialog.getByRole("textbox", { name: "超时秒数", exact: true }).fill("450")
  await dialog.getByLabel("程序路径", { exact: true }).fill(seed.argv[0])
  await dialog.getByLabel("额外参数", { exact: true }).fill(JSON.stringify(["-c", "import sys;print('浏览器执行成功');print('执行进度提示',file=sys.stderr)"]))
  const rejected = page.waitForResponse(response => response.url().endsWith("/api/v1/jobs") && response.status() === 422)
  await dialog.getByRole("button", { name: "预览变更" }).click()
  await rejected
  await expect(page.locator(".el-message--error")).toBeVisible()
  await expect(dialog.getByLabel("名称", { exact: true })).toHaveValue("浏览器测试任务")
  await dialog.getByLabel("工作目录", { exact: true }).fill(seed.cwd)
  await dialog.getByRole("button", { name: "预览变更" }).click()
  await expect(dialog.getByRole("button", { name: "确认保存" })).toBeVisible()
  await dialog.getByRole("button", { name: "确认保存" }).click()
  await expect(dialog).toHaveCount(0)
  const created = (await (await page.request.get("/api/v1/jobs/browser-test")).json()).data.job
  expect(created.timeout).toBe(450)
  await page.getByRole("button", { name: "浏览器测试任务", exact: true }).click()
  const summary = page.getByRole("table", { name: "任务概览", exact: true })
  await expect(summary.getByRole("cell", { name: "浏览器测试任务", exact: true })).toBeVisible()
  await expect(page.getByRole("button", { name: /返回列表/ })).toHaveCount(0)
